#!/usr/bin/env python3
"""Simulated-data panels for Fig. 3 (main text) and Fig. S3 (SI), in the Fig. 4 style.

DRL estimator, n = 1000, 100 replications of the two-stage synthetic DGP. For each unpersonalized
regime d = (d1, d2): RMSE against the true value, coverage of the true value by the model-based 95%
interval, and mean interval width, random vs the regime's stagewise adaptive design. The RMSE panel
adds the full-annotation DRL RMSE as a dotted reference line. Error bars are Monte Carlo SEs.

Main text uses the d = (0,0) RMSE and width panels; the SI uses all twelve.

Usage: python figures/fig_simulated_panels.py [--run-dir aggregates/synthetic] [--out-dir output]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402

HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(HERE), str(HERE.parent / "src")]
from plot_annotation_mc import curve_style  # noqa: E402
from sampler_names import ADAPTIVE_STAGEWISE  # noqa: E402

# Shipped trimmed per-replication synthetic results; the full run is regenerated by slurm/synthetic_stagewise.sbatch
# (results/synthetic/paper_two_stage_n1000_theorem_pilot30_reps100_crossfit5_stagewise).
RUN = HERE.parent / "aggregates" / "synthetic"
REGIMES = [(0, 0), (0, 1), (1, 0), (1, 1)]
PANELS = {
    "rmse": ("RMSE", "RMSE vs. true value"),
    "coverage": ("Coverage", "95% CI coverage of truth"),
    "width": ("CI Width", "Mean 95% interval width"),
}
REF_COLOR = "#9ca3af"


def summarize(g: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for budget, b in g.groupby("budget"):
        err2 = pd.to_numeric(b["squared_error"], errors="coerce").dropna()
        cov = pd.to_numeric(b["model_based_ci_covers_truth"], errors="coerce").dropna()
        width = pd.to_numeric(b["model_based_ci_width_95"], errors="coerce").dropna()
        rmse = float(np.sqrt(err2.mean()))
        rows.append({
            "budget": float(budget), "n_mc": int(len(err2)),
            "rmse": rmse, "rmse_se": float(err2.std(ddof=1) / (2.0 * rmse * np.sqrt(len(err2)))),
            "coverage": float(cov.mean()), "coverage_se": float(np.sqrt(cov.mean() * (1 - cov.mean()) / len(cov))),
            "width": float(width.mean()), "width_se": float(width.std(ddof=1) / np.sqrt(len(width))),
        })
    return pd.DataFrame(rows)


def plot_panel(frame: pd.DataFrame, key: str, title: str, out_stem: Path, full_rmse: float) -> None:
    fig, ax = plt.subplots(figsize=(2.5, 2.5))
    fig.subplots_adjust(left=0.26, right=0.98, top=0.84, bottom=0.24)
    plotted = ["random", ADAPTIVE_STAGEWISE]
    for sampler in plotted:
        g = frame[frame["sampler"].eq(sampler)].sort_values("budget")
        label, color, marker, linestyle = curve_style(sampler, plotted)
        ax.errorbar(100.0 * g["budget"], g[key], yerr=g[f"{key}_se"], color=color, linestyle=linestyle,
                    marker=marker, markersize=3.5, linewidth=1.5, elinewidth=0.8, capsize=2.5, capthick=1.0,
                    label=label)
    if key == "rmse":
        ax.axhline(full_rmse, color=REF_COLOR, linewidth=0.8, linestyle=":", label="Full annotation")
    if key == "coverage":
        ax.axhline(0.95, color=REF_COLOR, linewidth=0.8, linestyle=":")
        ax.set_ylim(0.7, 1.0)
    ax.set_xlabel("Annotation budget (%)", fontsize=8)
    ax.set_ylabel(PANELS[key][1], fontsize=8)
    ax.set_title(title, fontsize=9)
    ax.grid(True, axis="y", color="#e5e7eb", linewidth=0.8)
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.tick_params(axis="both", labelsize=7)
    ax.legend(frameon=False, loc="lower left" if key == "coverage" else "upper right", fontsize=7)
    fig.savefig(out_stem.with_suffix(".pdf"))
    fig.savefig(out_stem.with_suffix(".png"), dpi=300)
    plt.close(fig)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run-dir", type=Path, default=RUN)
    parser.add_argument("--sample-size", type=int, default=1000)
    parser.add_argument("--out-dir", type=Path, default=Path("output"))
    args = parser.parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)

    cols = ["sampler", "estimator", "sample_size", "d1", "d2", "budget", "squared_error",
            "model_based_ci_covers_truth", "model_based_ci_width_95"]
    res = pd.read_csv(args.run_dir / "results.csv", usecols=cols)
    res = res[res["estimator"].eq("drl") & res["sample_size"].eq(args.sample_size)]

    summaries = []
    for d1, d2 in REGIMES:
        g = res[res["d1"].eq(d1) & res["d2"].eq(d2)]
        full = g[g["sampler"].eq("full_data_krr")]
        full_rmse = float(np.sqrt(full["squared_error"].mean()))
        parts = []
        for raw, canon in [("random_50pct", "random"), (f"protocol_stagewise_regime_{d1}{d2}_50pct", ADAPTIVE_STAGEWISE)]:
            s = summarize(g[g["sampler"].eq(raw)])
            if s.empty:
                raise ValueError(f"No rows for sampler {raw!r}")
            parts.append(s.assign(sampler=canon))
        frame = pd.concat(parts, ignore_index=True).assign(d1=d1, d2=d2, full_rmse=full_rmse)
        summaries.append(frame)
        for key, (title, _) in PANELS.items():
            plot_panel(frame, key, f"Policy ({d1},{d2}): {title}", args.out_dir / f"synth_d{d1}{d2}_{key}", full_rmse)
    out = pd.concat(summaries, ignore_index=True)
    out.to_csv(args.out_dir / "sim_panels_summary.csv", index=False)
    print(f"Wrote {len(REGIMES) * len(PANELS)} panels and summary to {args.out_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
